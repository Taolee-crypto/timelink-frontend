const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const html=fs.readFileSync(path.join(__dirname,'../public/tilo-store-plans.html'),'utf8');
const receipt=fs.readFileSync(path.join(__dirname,'../public/store-payment-success.html'),'utf8');
const match=html.match(/<button\b[^>]*id="storePaymentConfirm"[^>]*>[\s\S]*?<\/button>/);
assert.ok(match,'Store payment confirm button must exist');
assert.doesNotMatch(match[0],/\bdisabled\b/,'Store card checkout button must not be permanently disabled');
assert.match(html,/\/api\/payment\/v5\/commercial-time\/quote/,'Server quote required');
assert.match(html,/\/api\/payment\/v5\/commercial-time\/toss\/prepare/,'Server order required');
assert.match(html,/\/api\/cafe\/my-channels/,'Checkout must select an owned store');
assert.match(html,/channel_id:storePayChannel\.value/,'Order must be scoped to store');
assert.match(html,/TossPayments\(order\.clientKey\)\.requestPayment\('카드'/,'Use existing Toss SDK');
assert.match(html,/store-payment-success\.html/,'Return to confirmation page');
assert.match(html,/localStorage\.getItem\('tl_token'\)/,'Use signed-in V5 token');
assert.match(receipt,/\/api\/payment\/v5\/commercial-time\/toss\/confirm/,'Confirm provider result server side');
assert.match(receipt,/\/api\/payment\/v5\/commercial-time\/balance/,'Display credited store balance');
assert.match(receipt,/history\.replaceState/,'Remove sensitive payment return parameters');
assert.match(html,/quote\.checkoutMode==='test'&&quote\.testCheckoutEnabled===true&&quote\.checkoutEnabled===true/,'Checkout must obey server test-mode availability');
assert.match(html,/storePayButton\.disabled=!available/,'Unavailable checkout must not be clickable');
assert.match(html,/if\(storePayButton\.disabled\|\|!storePaySelection/,'Click handler must recheck availability');
assert.doesNotMatch(html,/base=7900\*t\.factor/,'Client must not show prices inconsistent with server');
assert.match(html,/quoteEl\.textContent=summary/,'Server quote must replace local price approximation');
console.log('PASS store payment: quote, store owner, server checkout mode, Toss SDK, receipt and non-duplicated price');
