'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const src=fs.readFileSync('public/tilo-admin.html','utf8');
const scripts=[...src.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/gi)].map(x=>x[1]).filter(x=>x.trim());
assert.ok(scripts.length>0);
for(const script of scripts) new vm.Script(script);
assert.match(src,/id="tilo-operations"/);
assert.match(src,/id="tilo-operations-status"/);
assert.match(src,/\/api\/admin\/central-broadcast\/operations/);
assert.match(src,/Authorization:'Bearer '\+token\(\)/);
assert.match(src,/explicit_country_licensed_tracks/);
assert.match(src,/receiver_candidate_tracks/);
assert.match(src,/verified_airtime_events/);
assert.match(src,/approved_unposted_settlements/);
assert.match(src,/posted_settlements/);
assert.match(src,/실제 음원 송출 서버/);
assert.match(src,/운영 상태 조회 실패:/);
assert.match(src,/loadTiloOperations\(\)/);
assert.doesNotMatch(src,/실제 송출 시간 × 0\.3 TL/, 'administrator variable rate must not be displayed as fixed');
assert.match(src,/id="tilo-rights-country"/);
assert.match(src,/id="tilo-rights-list"/);
assert.match(src,/\/api\/admin\/central-broadcast\/stations\/.*\/audit/);
assert.match(src,/\/api\/admin\/central-broadcast\/stations\/.*\/grants/);
assert.match(src,/track\.can_grant===true/);
assert.match(src,/window\.confirm\(/);
assert.match(src,/owner.*권리|본인 소유권 확인/);
console.log('PASS TILO admin: inline JavaScript, admin operation evidence, rights, discounts and no false ON AIR');
