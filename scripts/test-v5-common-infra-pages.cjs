'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const admin=fs.readFileSync('public/admin.html','utf8');
const ledger=fs.readFileSync('public/v5-work-ledger.html','utf8');
const community=fs.readFileSync('public/community-admin.html','utf8');
const sidebar=fs.readFileSync('public/sidebar.js','utf8');
assert.ok(sidebar.includes('/admin.html'),'admin link not in current nav');
assert.ok(sidebar.includes('/v5-work-ledger.html'),'ledger not in current nav');
assert.ok(sidebar.includes('/community-admin.html'),'moderation not in current nav');
assert.ok(admin.includes("'/api/admin/finance/ledger-integrity'")||admin.includes("+'/api/admin/finance/ledger-integrity'"),'admin finance audit missing');
assert.ok(admin.includes('/api/admin/session'),'admin signed session check absent');
assert.ok(admin.includes('href="/v5-work-ledger.html"'));
assert.ok(admin.includes('관리자 SQL 콘솔은 조회 전용'));
assert.ok(ledger.includes('const workLedgerAPI='),'server-ledger is missing');
assert.ok(ledger.includes('loadServerWorkLedger'),'ledger API should load server data');
assert.ok(ledger.includes('saveServerWorkLedger'),'server ledger must have authorized save path');
assert.ok(ledger.includes('alignStoreRoleTasks'),'ledger must preserve category alignment');
assert.ok(community.includes('/api/v5/community/moderation/reports'),'community API path');
assert.ok(community.includes('Authorization:')&&community.includes('Bearer '),'moderation auth missing');
assert.ok(community.includes("textContent=report.body"),'render untrusted moderation text safely');
assert.ok(!community.includes('innerHTML=report.body'),'moderation should not inject report body');
const communityScript=community.match(/<script>\s*([\s\S]*?)<\/script>/);
assert.ok(communityScript,'community inline script missing');
new vm.Script(communityScript[1],{filename:'community-admin.html'});
const ledgerScript=ledger.split('<script>').at(-1).split('</script>')[0];
new vm.Script(ledgerScript,{filename:'v5-work-ledger.html'});
console.log('PASS infrastructure admin/ledger/moderation route links, signed auth contracts, safe report rendering, script parsing');
