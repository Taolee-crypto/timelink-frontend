'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const radio=fs.readFileSync('public/radio.html','utf8');
const admin=fs.readFileSync('public/tilo-admin.html','utf8');
for(const html of [radio,admin]){
 const inline=[...html.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/gi)].map(x=>x[1]).filter(Boolean);
 assert.ok(inline.length,'inline script missing');
 for(const script of inline)new vm.Script(script);
}
assert.match(radio,/const requestedRadioCountry=new URLSearchParams\(location\.search\)\.get\('country'\)/);
assert.match(radio,/Object\.prototype\.hasOwnProperty\.call\(names,requestedRadioCountry\)/);
assert.match(radio,/id="tilo-promotion-lineup"/);
assert.match(radio,/data\.promoted_count/);
assert.match(radio,/data\.ordinary_count/);
assert.match(radio,/홍보 예산 확보곡/);
assert.match(radio,/일반 보충곡/);
assert.match(radio,/TIME FREE 우선/);
assert.match(radio,/청취 1초당 1TL/);
assert.doesNotMatch(radio,/개인 TL 차감 없음|청취자 TL 차감 없음/);
assert.doesNotMatch(radio,/id="tilo-rights-setup"/,'ordinary broadcast cannot be gated by admin bulk grants');
assert.doesNotMatch(radio,/toggleTiloRightsSetup/);
assert.doesNotMatch(radio,/별도 국가별 승인 구매/);
assert.match(admin,/id="tilo-rights-select-all"/);
assert.match(admin,/국가별 추가 권리 기록 \(선택 사항\)/);
assert.match(admin,/여기서 곡을 추가로 승인할 필요는 없습니다/);
assert.match(admin,/promotion_eligible_tracks/);
assert.match(admin,/ordinary_fallback_tracks/);
assert.match(admin,/별도 국가권리 기록/);
assert.match(admin,/NO_RIGHTS_DECLARED_V5_STATION_TRACKS/);
assert.match(admin,/rights_confirmed:true/,'an explicit grant is still possible only with consent');
assert.match(admin,/window\.confirm\(/,'explicit grant must not be automatic');
console.log('PASS TILO original promoted-first plus ordinary fallback, no mandatory admin country grants, rights revocations preserved');
