'use strict';
const fs=require('node:fs');
const assert=require('node:assert/strict');
const vm=require('node:vm');
const html=fs.readFileSync('public/dashboard.html','utf8');
assert.ok(html.includes('POC 계산 후 TLC 채굴'),'Development stage mint action must be visible');
assert.ok(html.includes('TLC 채굴 · 개발 단계'),'Development stage clearly disclosed');
assert.ok(html.includes("API + '/api/eco/activity'"),'POC input is read from the server');
assert.ok(html.includes("API + '/api/eco/mine-tlc'"),'The button must call the fixed atomic mining endpoint');
assert.ok(html.includes("JSON.stringify({})"),'No user-supplied TLC quantity is required');
assert.ok(html.includes("mined.code==='ALREADY_MINED_TODAY'"),'Daily duplicate claim must show friendly feedback');
assert.ok(html.includes("loadMiningHistory();"),'History must refresh after successful mining');
const script=html.match(/async function calcMining\(\)\{[\s\S]*?\n\}\n/);
assert.ok(script,'The mining function must still exist');
new vm.Script(script[0],{filename:'dashboard-mine.js'});
console.log('PASS POC UI: daily mining restored, no client amount, dedup state and history refresh');
