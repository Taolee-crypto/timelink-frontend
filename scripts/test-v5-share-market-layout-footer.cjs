'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const share=fs.readFileSync('public/shareplace.html','utf8');
const commonFooter=fs.readFileSync('public/_shared/footer.js','utf8');
const ledger=fs.readFileSync('public/v5-work-ledger.html','utf8');
assert.match(share,/\.page-content\{[^}]*grid-template-columns:minmax\(0,1fr\)/);
assert.match(share,/\.page-main\{min-width:0\}/);
assert.ok(!share.includes('grid-template-columns:70% 30%'),'advertising sidebar column still reserves 30%');
assert.ok(!share.includes('class="page-ads"'),'advertising column still rendered');
assert.ok(!share.includes('.page-ads{'),'retired advertisement style still appears');
assert.ok(!share.includes('씨엠피 주식회사'),'old corporation cannot appear in SharePlace footer');
assert.ok(!share.includes("['ads.html','광고 센터']"),'retired ads link');
assert.ok(!share.includes("['dj-guide.html','DJ 가이드']"),'retired DJ link');
assert.ok(!share.includes("['advertiser.html','광고주 센터']"),'retired advertiser link');
assert.ok(share.includes('<script src="/_shared/footer.js" defer></script>'),'shared footer script must mount');
assert.ok(commonFooter.includes('틸로그룹 · TILO Group'));
assert.ok(commonFooter.includes('(주)틸로코리아'));
assert.ok(commonFooter.includes("document.querySelectorAll('#tl-dynamic-footer,.gate-footer')"));
assert.match(share,/id="fileGrid"/);assert.match(share,/id="filePager"/);
assert.ok(share.includes('var _curPage = 1, _perPage = 20'),'20 tracks per page contract');
assert.ok(ledger.includes("'/shareplace.html'"),'work ledger map needs SharePlace page');
const scripts=[...share.matchAll(/<script(?:\s+[^>]*)?>([\s\S]*?)<\/script>/g)].map(m=>m[1]).filter(x=>x.trim());
for(const js of scripts)new vm.Script(js,{filename:'shareplace-inline.js'});
console.log('PASS SharePlace 100% music area, 20 item pager, shared legal footer, no legacy DJ/ads and valid scripts');
